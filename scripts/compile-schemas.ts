// The shipped kinds' schema validators compiled ahead of time (#51, D16), for the engine in a page,
// whose Content Security Policy forbids compiling code at run time (Ajv's default). One module per
// kind in packages/kinds/generated, and schemas.json naming each schema's export and the kind's
// fingerprint, which core checks before using them. Run by `npm run build:template`; a test fails when
// they're stale (packages/kinds/test/compiled-schemas.test.ts).
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import Ajv2020 from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";
import { AJV_OPTIONS, kindByKey, schemaFingerprint, schemasOf } from "@writer/core";
import { KINDS, registerKinds } from "@writer/kinds";

const out = fileURLToPath(new URL("../packages/kinds/generated/", import.meta.url));

/** Each shipped kind's validators as module code, and what's in them. */
export function compiledSchemas(): { files: Map<string, string>; meta: Record<string, { fingerprint: string; exports: Record<string, string> }> } {
  registerKinds();
  const files = new Map<string, string>();
  const meta: Record<string, { fingerprint: string; exports: Record<string, string> }> = {};
  for (const { key } of KINDS) {
    const kind = kindByKey(key);
    const { common, schemas } = schemasOf(kind);
    const ajv = new Ajv2020.default({ ...AJV_OPTIONS, code: { source: true, esm: true } });
    ajv.addSchema(common);
    const exports: Record<string, string> = {};
    const refs: Record<string, string> = {};
    for (const [i, [name, schema]] of schemas.entries()) {
      const id = (schema as { $id: string }).$id;
      ajv.addSchema(schema);
      exports[name] = `v${i}`;
      refs[`v${i}`] = id;
    }
    files.set(`schemas-${key}.js`, `// Generated by scripts/compile-schemas.ts from the ${kind.label}'s schemas: don't edit.\n${asModule(standaloneCode.default(ajv, refs))}`);
    files.set(`schemas-${key}.d.ts`, `// Generated by scripts/compile-schemas.ts: don't edit.\nimport type { ValidateFunction } from "ajv";\n${Object.values(exports).map((v) => `export declare const ${v}: ValidateFunction;`).join("\n")}\n`);
    meta[key] = { fingerprint: schemaFingerprint(kind), exports };
  }
  files.set("schemas.json", `${JSON.stringify(meta, null, 2)}\n`);
  return { files, meta };
}

/** Ajv's standalone code requires its runtime helpers even as a module: imports, for a browser's bundle. */
function asModule(code: string): string {
  const imports = new Map<string, string>();
  const body = code.replace(/require\("([^"]+)"\)/g, (_, path: string) => {
    if (!imports.has(path)) imports.set(path, `runtime${imports.size}`);
    return imports.get(path)!;
  });
  const head = [...imports].map(([path, name]) => `import ${name} from "${path}.js";`).join("\n");
  // A CommonJS default import is module.exports in Node and its default in a bundler: the function either way.
  const unwrap = "const helper = (m) => (typeof m === \"function\" ? m : typeof m.default === \"function\" ? m.default : m.default.default);";
  const used = body.replace(/^"use strict";/, "").replace(/\b(runtime\d+)\.default\b/g, "helper($1)");
  return `${head}\n${unwrap}\n${used}`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  for (const [name, text] of compiledSchemas().files) writeFileSync(join(out, name), text);
  console.log(`Wrote packages/kinds/generated (${KINDS.map((k) => k.key).join(", ")})`);
}
