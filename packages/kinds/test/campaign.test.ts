import { fileURLToPath } from "node:url";
import { backlinks, compileBook, entriesOf, graphTypes, kindByKey, layoutOf, loadBook, locationProfile, PLAIN_LAYOUT, relationshipsAt, sceneFacts, typePlural, validate, vocabulary, withModules } from "@writer/core";
import { graphAt } from "@writer/core/diagrams";
import { snapshots } from "@writer/core/snapshots";
import { nodeSource } from "@writer/core/node";
import { describe, expect, it } from "vitest";
import { campaign } from "../src/index.ts";

/** The Campaign kind (#41): arcs of sessions, a codex of NPCs, player characters, locations, factions, items and quests. */

const SAMPLE = fileURLToPath(new URL("../../../examples/sample-campaign", import.meta.url));

describe("the Campaign kind", () => {
  it("is registered with presence and story time, and none of the Novel's story-only modules", () => {
    const kind = kindByKey("campaign");
    expect(kind).toBe(withModules(campaign));
    expect(kind.modules).toEqual(["presence", "story-time"]);
    expect(kind.fields.map((f) => f.key)).toEqual(["when", "party", "npcs", "locations", "factions", "items", "quests", "entities"]);
    expect(layoutOf(kind)).toBe(PLAIN_LAYOUT);
  });

  it("says a game master's words", () => {
    const kind = kindByKey("campaign");
    const w = vocabulary(kind);
    expect([w.book.a, w.piece.count(3), w.level("arc").a, w.codex.One, w.entity.count(2)]).toEqual(["a campaign", "3 sessions", "an arc", "Codex", "2 entries"]);
    expect(kind.entityTypes.map(typePlural)).toEqual(["NPCs", "Player characters", "Locations", "Factions", "Items", "Quests"]);
  });

  it("has a prefix of its own for the book, the arc, the session and each type", () => {
    const own = [campaign.prefix, ...campaign.levels.map((l) => l.prefix), campaign.piece.prefix, ...campaign.entityTypes.map((t) => t.prefix)];
    expect(new Set(own).size).toBe(own.length);
  });

  it("reads the sample campaign clean: its sessions, who and what is in them, quests as threads", async () => {
    const r = await validate(nodeSource(SAMPLE));
    expect(r.diagnostics).toEqual([]);
    const book = r.novel;
    expect(book.pieces.map((p) => [p.title, p.status])).toEqual([["Session 1", "played"], ["Session 2", "prepped"]]);
    expect(entriesOf(book, book.pieces[1]!, "npc")).toEqual(["npc_ma7ra1", "npc_v0ss01"]);
    expect(backlinks(book, "qst_be11s0").scenes.map((s) => s.scene.title)).toEqual(["Session 1", "Session 2"]);
    // A quest begins in the first session it's in; NPCs are people, first seen where they turn up.
    expect(sceneFacts(book, "ses_0ne001")).toEqual(expect.arrayContaining(["The book's first session.", "Why the Bell Rings begins here."]));
    expect(sceneFacts(book, "ses_tw0002")).toContain("First appearance of Voss.");
  });

  it("changes an NPC's allegiance at a session, as the graph shows it", async () => {
    const book = await loadBook(nodeSource(SAMPLE));
    const factionOf = (session: string) => relationshipsAt(book, session).filter((r) => r.from === "npc_ma7ra1" && r.type === "member-of").map((r) => r.to);
    expect(factionOf("ses_0ne001")).toEqual(["fac_watch0"]);
    expect(factionOf("ses_tw0002")).toEqual(["fac_t1de00"]);
    // The graph shows the factions with the people, until it's filtered; so does the diagram in the book.
    expect(graphTypes(book)).toEqual(["npc", "pc", "faction"]);
    expect(graphAt(book, "ses_tw0002").edges.map((e) => e.label)).toEqual(["Allied with", "Member of", "Member of"]);
    const files = snapshots(book);
    expect([...files.keys()]).toEqual(["diagrams/relationships.svg", "diagrams/presence-npcs.svg", "diagrams/presence-quests.svg", "diagrams/timeline.svg", "diagrams/README.md"]);
    expect(files.get("diagrams/README.md")).toContain("Generated by Writer from the campaign's files");
    expect(files.get("diagrams/README.md")).toContain('npc_ma7ra1 -->|"Member of"| fac_t1de00');
  });

  it("says who comes to a location: the party and the NPCs there", async () => {
    const book = await loadBook(nodeSource(SAMPLE));
    expect(locationProfile(book, "loc_be1fry").visitors.map((v) => v.name)).toEqual(["Aya", "Kith", "Marta Hollin", "Voss"]);
  });

  it("compiles plainly: its arc headed by its title", async () => {
    const book = await loadBook(nodeSource(SAMPLE));
    const compiled = await compileBook(book, nodeSource(SAMPLE));
    expect(compiled.chapters.map((c) => c.heading)).toEqual(["The Drowned Bell"]);
  });
});
