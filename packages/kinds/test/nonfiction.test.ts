import { fileURLToPath } from "node:url";
import { backlinks, compileBook, entriesOf, graphTypes, kindByKey, layoutOf, loadBook, PLAIN_LAYOUT, typePlural, validate, vocabulary, withModules } from "@writer/core";
import { snapshots } from "@writer/core/snapshots";
import { nodeSource } from "@writer/core/node";
import { render } from "@writer/export";
import { strFromU8, unzipSync } from "fflate";
import { getDocument } from "pdfjs-dist/legacy/build/pdf.mjs";
import { describe, expect, it } from "vitest";
import { nonfiction } from "../src/index.ts";

/** The Non-fiction kind (#57): parts and chapters of sections, an index of sources, people, concepts and claims. */

const SAMPLE = fileURLToPath(new URL("../../../examples/sample-nonfiction", import.meta.url));
const DATE = new Date("2026-10-22T12:00:00Z");

describe("the Non-fiction kind", () => {
  it("is registered with presence and citations, and none of the Novel's story modules", () => {
    const kind = kindByKey("nonfiction");
    expect(kind).toBe(withModules(nonfiction));
    expect(kind.modules).toEqual(["presence", "citations"]);
    expect(kind.fields.map((f) => f.key)).toEqual(["sources", "people", "concepts", "claims", "entities"]);
    expect(layoutOf(kind)).toBe(PLAIN_LAYOUT);
  });

  it("says a non-fiction writer's words", () => {
    const w = vocabulary(kindByKey("nonfiction"));
    expect([w.book.a, w.piece.count(3), w.level("chapter").a, w.level("part").a, w.codex.One, w.entity.count(2)]).toEqual(["a non-fiction book", "3 sections", "a chapter", "a part", "Index", "2 entries"]);
    expect(nonfiction.entityTypes.map(typePlural)).toEqual(["Sources", "People", "Concepts", "Claims"]);
  });

  it("has a prefix of its own for the book, each level, the section and each type", () => {
    const own = [nonfiction.prefix, ...nonfiction.levels.map((l) => l.prefix), nonfiction.piece.prefix, ...nonfiction.entityTypes.map((t) => t.prefix)];
    expect(new Set(own).size).toBe(own.length);
  });

  it("reads the sample book clean: its sections, what they draw on, concepts as threads", async () => {
    const r = await validate(nodeSource(SAMPLE));
    expect(r.diagnostics).toEqual([]);
    const book = r.novel;
    expect(book.pieces.map((p) => [p.title, p.status])).toEqual([
      ["A despised creature", "revised"],
      ["Ten tons an acre", "draft"],
      ["Stones sink", "outline"],
    ]);
    expect(entriesOf(book, book.pieces[1]!, "source")).toEqual(["src_d4rw1n"]);
    expect(backlinks(book, "con_ca5t50").scenes.map((s) => s.scene.title)).toEqual(["Ten tons an acre", "Stones sink"]);
    expect(graphTypes(book)).toEqual(["person", "concept", "claim"]);
  });

  it("draws which sources and concepts each chapter turns to, and how the ideas relate", async () => {
    const book = await loadBook(nodeSource(SAMPLE));
    const files = snapshots(book);
    expect([...files.keys()]).toEqual(["diagrams/relationships.svg", "diagrams/presence-sources.svg", "diagrams/presence-concepts.svg", "diagrams/README.md"]);
    expect(files.get("diagrams/README.md")).toContain("Generated by Writer from the non-fiction book's files");
    expect(files.get("diagrams/README.md")).toContain('per_darw1n -->|"Argues"| clm_t0p501');
  });

  it("compiles to DOCX, EPUB and PDF, its chapters headed by their titles", async () => {
    const book = await loadBook(nodeSource(SAMPLE));
    const compiled = await compileBook(book, nodeSource(SAMPLE));
    expect(compiled.chapters.map((c) => c.heading)).toEqual(["Castings", "Burial"]);
    // Each section headed by its title, beneath its chapter's: no breaks between them.
    expect(compiled.chapters[0]!.blocks.filter((b) => b.kind === "heading" || b.kind === "break")).toEqual([
      { kind: "heading", level: 1, runs: [{ text: "A despised creature" }] },
      { kind: "heading", level: 1, runs: [{ text: "Ten tons an acre" }] },
    ]);
    const line = "more than ten tons of dry earth passed through their bodies";
    // Its footnote, the chapter's note (#58).
    expect(compiled.chapters[0]!.notes).toEqual([{ number: 1, blocks: [{ kind: "paragraph", runs: [{ text: "Darwin, Vegetable Mould. He gives the figure in metric too: 10,516 kilogrammes." }] }] }]);
    // Its bibliography, from the citations module (#59).
    expect(compiled.back.map((m) => m.title)).toEqual(["Bibliography"]);

    const docx = unzipSync((await render(compiled, "docx", { date: DATE })).bytes);
    expect(strFromU8(docx["word/document.xml"]!)).toContain(line);
    expect(strFromU8(docx["word/footnotes.xml"]!)).toContain("10,516 kilogrammes");
    const epub = unzipSync((await render(compiled, "epub", { date: DATE })).bytes);
    expect(Object.entries(epub).some(([path, bytes]) => path.endsWith(".xhtml") && strFromU8(bytes).includes(line))).toBe(true);
    const pdf = await getDocument({ data: new Uint8Array((await render(compiled, "pdf", { date: DATE })).bytes) }).promise;
    let text = "";
    for (let i = 1; i <= pdf.numPages; i++) text += (await (await pdf.getPage(i)).getTextContent()).items.map((x) => ("str" in x ? x.str : "")).join(" ") + " ";
    expect(text.replace(/\s+/g, " ")).toContain("Ten tons an acre");
    expect(text).toContain("Burial");
    expect(text).toContain("10,516 kilogrammes");
    expect(text).toContain("Bibliography");
  });
});
