import { fileURLToPath } from "node:url";
import { JSDOM } from "jsdom";
import { describe, expect, it } from "vitest";
import { loadBook } from "../src/index.ts";
import { nodeSource } from "../src/node.ts";
import { relationshipMermaid, snapshots } from "../src/snapshots.ts";

const novel = await loadBook(nodeSource(fileURLToPath(new URL("../../../examples/sample-novel", import.meta.url))));

describe("snapshots", () => {
  it("say the relationship graph in Mermaid, as the app holds it at a scene", () => {
    expect(relationshipMermaid(novel, "sc_0d9wm4")).toBe(
      [
        "flowchart LR",
        '  char_7f3k2q["Ada Varn"]',
        '  char_b3n0vs["Ben Varn"]',
        '  char_m1re1a["Mirela Kost"]',
        '  char_t0ma5h["Tomas Hale"]',
        '  char_7f3k2q ---|"Sibling of"| char_b3n0vs',
        '  char_7f3k2q -.-|"Rivals with"| char_b3n0vs',
        '  char_t0ma5h -->|"Mentor of"| char_7f3k2q',
        "  linkStyle 0 stroke:#2a78d6,stroke-width:2px",
        "  linkStyle 1 stroke:#e34948,stroke-width:2px",
        "  linkStyle 2 stroke:#eda100,stroke-width:2px",
        "",
      ].join("\n"),
    );
  });

  it("write well-formed SVGs with the diagrams' labels, and an overview embedding them", () => {
    const files = snapshots(novel);
    expect([...files.keys()]).toEqual([
      "diagrams/relationships.svg",
      "diagrams/plotlines.svg",
      "diagrams/presence-characters.svg",
      "diagrams/presence-themes.svg",
      "diagrams/timeline.svg",
      "diagrams/README.md",
    ]);
    for (const [path, text] of files) {
      if (!path.endsWith(".svg")) continue;
      const doc = new new JSDOM("").window.DOMParser().parseFromString(text, "image/svg+xml");
      expect(doc.querySelector("parsererror"), path).toBeNull();
      expect(text, path).toContain("Generated by Writer");
    }
    expect(files.get("diagrams/relationships.svg")).toContain(">Allied with<");
    expect(files.get("diagrams/plotlines.svg")).toContain(">Ben&apos;s Debt<".replace("&apos;", "'"));
    expect(files.get("diagrams/timeline.svg")).toContain("6th · flashback");
    const md = files.get("diagrams/README.md")!;
    expect(md).toMatch(/^# Diagrams of The Bridge at Varn\n/);
    for (const svg of ["relationships", "plotlines", "presence-characters", "presence-themes", "timeline"]) expect(md).toContain(`(${svg}.svg)`);
    expect(md.match(/```mermaid\n/g)).toHaveLength(3);
  });

  it("are the same bytes for the same novel", () => {
    expect([...snapshots(novel)]).toEqual([...snapshots(novel)]);
  });
});
